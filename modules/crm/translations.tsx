export function useCrmText() {
  const { locale } = useLanguage();
  return (text: string) => (locale === "bn" ? (bangla[text] ?? text) : text);
}
export function CrmText({ text }: { text: string }) {
  const tr = useCrmText();
  return <>{tr(text)}</>;
}
